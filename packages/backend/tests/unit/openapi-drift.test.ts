import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { parse as parseYaml } from 'yaml';
import { describe, expect, it } from 'vitest';
import { generateSpec } from '../../src/openapi/generate-spec';

describe('OpenAPI drift gate', () => {
	it('all reference openapi.yaml paths are implemented', () => {
		const generated = generateSpec();
		const generatedPaths = ((generated.paths as Record<string, unknown>) ?? {});
		const generatedPathKeys = Object.keys(generatedPaths).sort();

		const reference = loadReferenceSpec();
		const referencePaths = ((reference.paths as Record<string, unknown>) ?? {});
		const referencePathKeys = Object.keys(referencePaths).sort();

		const missingFromGenerated = referencePathKeys.filter((p) => !generatedPathKeys.includes(p));

		expect(
			missingFromGenerated,
			`OpenAPI drift detected.\n` +
				`Paths in reference openapi.yaml but NOT auto-generated by @openapi annotations: ${missingFromGenerated.join(', ') || 'none'}`,
		).toEqual([]);
	});
});

function loadReferenceSpec(): { paths?: Record<string, unknown> } {
	const candidates = [
		path.resolve(process.cwd(), 'docs', 'openapi.yaml'),
		path.resolve(process.cwd(), '..', 'docs', 'openapi.yaml'),
		path.resolve(process.cwd(), '..', '..', 'docs', 'openapi.yaml'),
		path.resolve(__dirname, '..', '..', '..', '..', 'docs', 'openapi.yaml'),
	];

	for (const candidate of candidates) {
		if (!existsSync(candidate)) {
			continue;
		}

		const raw = readFileSync(candidate, 'utf8');
		const parsed = parseYaml(raw);

		if (parsed !== null && typeof parsed === 'object') {
			return parsed as { paths?: Record<string, unknown> };
		}
	}

	throw new Error('Failed to locate docs/openapi.yaml for drift check.');
}
